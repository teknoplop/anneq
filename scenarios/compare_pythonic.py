"""Rerun the report's scenarios with src/anneq.py and compare with the fixed line port.

uv run --python 3.15 --no-project --with numpy --with scipy python scenarios/compare_pythonic.py
    [--jobs 8] [--only SUBSTR] [--report-only]
Same jobs and settings as scenarios/run_fixed.py (run_scenarios.JOBS, re-tuned RNN rates, BPBC 20
trials, seed 1000). src/anneq.py draws from numpy's generator, not the 1995 rand(), so the check is
statistical: for BER and final error, z = (pythonic - fixed) / (sqrt(2) * SE), where SE is the
standard error of the pythonic mean over trials (floored at the binomial SE for BER), taken as the
same for both runs. A point is within tolerance when |z| < 3.
Output: results/pythonic/results.csv, curves/, compare.md.
REMOTE=host: run the jobs on host in ~/anneq-runs/pythonic/ and copy the results back.
"""
import argparse, concurrent.futures as cf, csv, math, os, pathlib, subprocess, sys, time

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "scenarios")]
import anneq  # noqa: E402
import run_scenarios as rs  # noqa: E402
from run_fixed import RNN_ETA_FIXED  # noqa: E402

OUT = ROOT / "results" / "pythonic"
REF = ROOT / "results" / "fixed"
Z_MAX = 3.0
CHANNEL = {tuple(rs.CH1): "ch1", tuple(rs.CH2): "ch2", tuple(rs.REAL): "tel"}


def model_and_exp(prog, p):
    ch = CHANNEL[tuple(p["ch"])]
    exp = anneq.Experiment(channel=ch, snr_db=p["snr"], delay=p.get("delay", 0), seed=rs.SEED,
                           trials=20 if prog == "BPBC" else rs.TRIALS)
    match prog:
        case "LMS": model = anneq.LMS(p["taps"], p["eta"])
        case "RNN": model = anneq.RNN(p["inputs"], p["nodes"], RNN_ETA_FIXED["tel" if ch == "tel" else "toy"])
        case "RB": model = anneq.RBF(p["inputs"], p["nodes"], p["width"])
        case _: model = anneq.BP(p["n"], p["lr"], p["mom"], p["epochs"], p["bits"])
    return model, exp


def mean_se(xs):
    n = len(xs)
    if n == 0:
        return math.nan, math.nan
    m = sum(xs) / n
    return m, (math.sqrt(sum((x - m) ** 2 for x in xs) / (n - 1) / n) if n > 1 else math.nan)


def run_job(job):
    scen, prog, lab, p = job
    model, exp = model_and_exp(prog, p)
    t0 = time.time()
    s = anneq.simulate(model, exp)
    finals = [float(t.curve[-anneq.FINAL_WINDOW:].mean()) for t in s.trials if t.passed and t.curve is not None]
    ber_m, ber_se = mean_se([t.ber for t in s.trials])
    binom = math.sqrt(max(ber_m * (1 - ber_m), 1e-12) / (exp.trials * exp.test_bits))
    fe_m, fe_se = mean_se(finals)
    row = dict(scenario=scen, setting=lab, trials=exp.trials, ber=ber_m, ber_se=max(ber_se, binom),
               final_err=fe_m if finals else "", final_se=fe_se if finals else "",
               fail_per_trial=s.fails_per_trial, gaveup_per_trial=s.gaveup, secs=round(time.time() - t0, 1))
    return row, s.curve


def run_all(jobs, n):
    (OUT / "curves").mkdir(parents=True, exist_ok=True)
    rows, t0 = [], time.time()
    with cf.ProcessPoolExecutor(n) as ex:
        futs = {ex.submit(run_job, j): j for j in jobs}
        for k, f in enumerate(cf.as_completed(futs), 1):
            row, curve = f.result()
            rows.append(row)
            if curve is not None:
                (OUT / "curves" / f"{row['scenario']}__pythonic__{row['setting']}.txt").write_text(
                    "\n".join(f"{v:.7g}" for v in curve) + "\n")
            print(f"[{k}/{len(jobs)}] {row['scenario']} {row['setting']} ber={row['ber']:.4g} {row['secs']} s", flush=True)
    print(f"{len(jobs)} jobs in {time.time() - t0:.0f} s on {n} workers", flush=True)
    path = OUT / "results.csv"
    old = [r for r in csv.DictReader(open(path))] if path.exists() else []
    new = {(r["scenario"], r["setting"]) for r in rows}
    rows = [r for r in old if (r["scenario"], r["setting"]) not in new] + rows
    rows.sort(key=lambda r: (r["scenario"], r["setting"]))
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[-1]))
        w.writeheader(); w.writerows(rows)


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return math.nan


def z(a, b, se):
    if a == b:
        return 0.0
    return (a - b) / (math.sqrt(2) * se) if se and se > 0 else math.inf


def fmt(v, spec=".3g"):
    return "–" if math.isnan(v) else format(v, spec)


def report():
    mine = list(csv.DictReader(open(OUT / "results.csv")))
    lines = ["# src/anneq.py against the fixed line port (results/fixed/, impl pyfix)", "",
             "Generated by `scenarios/compare_pythonic.py`. Same scenarios and settings as `results/fixed/`;",
             f"z = difference / (√2·SE of the pythonic mean over trials); within tolerance when |z| < {Z_MAX:g}.",
             "Final error is the mean of the last 100 points of the ensemble learning curve (epochs for BPBC).", "",
             "| scenario | setting | trials | BER fixed | BER pythonic | z | final err fixed | final err pythonic | z | gave up fixed / pythonic | ok |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    n_ok = n_all = 0
    outside = []
    for r in mine:
        refs = [x for x in csv.DictReader(open(REF / f"{r['scenario']}.csv"))
                if x["impl"] == "pyfix" and x["setting"] == r["setting"]]
        if not refs:
            continue
        ref = refs[0]
        pooled = max((num(r["ber"]) + num(ref["ber"])) / 2, 0.5 / (int(r["trials"]) * 10_000))
        binom = math.sqrt(pooled * (1 - pooled) / (int(r["trials"]) * 10_000))   # floor for rare errors
        zb = z(num(r["ber"]), num(ref["ber"]), max(num(r["ber_se"]), binom))
        fe, fr = num(r["final_err"]), num(ref["final_err"])
        zf = math.nan if math.isnan(fe) or math.isnan(fr) else z(fe, fr, num(r["final_se"]))
        ok = abs(zb) < Z_MAX and (math.isnan(zf) or abs(zf) < Z_MAX)
        n_all += 1; n_ok += ok
        if not ok:
            outside.append(f"{r['scenario']} {r['setting']}")
        lines.append(f"| {r['scenario']} | {r['setting']} | {r['trials']} | {fmt(num(ref['ber']))} | {fmt(num(r['ber']))} | "
                     f"{fmt(zb, '+.1f')} | {fmt(fr)} | {fmt(fe)} | {fmt(zf, '+.1f')} | "
                     f"{fmt(num(ref['gaveup_per_trial']), '.2f')} / {fmt(num(r['gaveup_per_trial']), '.2f')} | "
                     f"{'yes' if ok else '**no**'} |")
    lines[5:5] = [f"**{n_ok} of {n_all} points within tolerance.**" +
                  (f" Outside: {', '.join(outside)}." if outside else ""), ""]
    (OUT / "compare.md").write_text("\n".join(lines + ["", NOTES]) + "\n")
    print(f"{n_ok}/{n_all} within tolerance; outside: {outside}")


NOTES = """## Points outside tolerance

The scenarios share one seed (1000) across a family's SNR or tap settings, so the rows of a family
are correlated and a reference that drew a high or low sample shows up in several rows at once.
Checked by rerunning both implementations with other seeds (100 trials; BPBC 20):

- **fig5_3 taps=3, extra_ada10_real snr=6 (final error, z of about -3.5).** The reference at seed 1000 is the
  highest of six line-port seeds (taps=3: 0.0237 against 0.0226-0.0234 for seeds 1-5; telephone 6 dB:
  0.534 against 0.512-0.534), and src/anneq.py at seed 1000 is at the low end of its own spread
  (0.0227-0.0233; 0.519-0.534). The ranges overlap; the BERs agree (|z| < 1.1).
- **bp_ch1 snr=10/14/21.** BPBC trains 40 patterns for 1000 epochs, so per-trial results have a heavy
  tail: a trial that lands in a poor minimum gives a final error near 0.1 or a BER near 0.1 and dominates a
  20-trial mean, and the SE estimated from 20 trials misses it. The line port's 21 dB BER of 0.006 at seed
  1000 is such a draw: with seeds 1-6 it gives 5e-6 to 9.5e-5, and src/anneq.py gives 0 to 1.5e-3. The
  10 dB final error ranges over 5e-6 to 9e-3 between seeds of src/anneq.py, which contains the reference's 5e-3.
"""


def remote(host, argv):
    base = "anneq-runs/pythonic"
    subprocess.run(["ssh", host, f"mkdir -p ~/{base}/src ~/{base}/scenarios ~/{base}/results/pythonic"], check=True)
    subprocess.run(["rsync", "-a", f"{ROOT}/src/anneq.py", f"{host}:{base}/src/"], check=True)
    subprocess.run(["rsync", "-a", *(f"{ROOT}/scenarios/{f}" for f in ("compare_pythonic.py", "run_fixed.py", "run_scenarios.py")),
                    f"{host}:{base}/scenarios/"], check=True)
    subprocess.run(["ssh", host, f"cd ~/{base} && /opt/homebrew/bin/uv run --python 3.15 --no-project --with numpy "
                                 f"--with scipy python scenarios/compare_pythonic.py --no-report {' '.join(argv)}"], check=True)
    OUT.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsync", "-a", f"{host}:{base}/results/pythonic/", f"{OUT}/"], check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--only", default="")
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--no-report", action="store_true")
    a = ap.parse_args()
    if not a.report_only:
        if host := os.environ.pop("REMOTE", ""):
            remote(host, [f"--jobs={a.jobs}"] + ([f"--only={a.only}"] if a.only else []))
        else:
            jobs = [j for j in rs.JOBS if a.only in j[0]]
            jobs.sort(key=lambda j: (j[1] != "RNN" or j[3]["ch"] != rs.REAL, j[1] != "RNN"))   # longest first
            run_all(jobs, a.jobs)
    if not a.no_report:
        report()


if __name__ == "__main__":
    main()
